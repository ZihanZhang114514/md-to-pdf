def detect_lang(text: str) -> str:
    cjk = len(CJK_RE.findall(text))
    if not cjk:
        return "en"
    latin = len(re.findall(r"[A-Za-z]", text))
    return "zh" if cjk >= 20 and cjk * 2 >= latin else "en"


def build_document(md: str, title: str, subtitle: str, lang: str,
                   fonts: dict[str, str]) -> tuple[str, TexConverter]:
    tex = TexConverter()
    render = Renderer(lang, tex)
    indent = "#h(2em)" if lang == "zh" else ""

    serif = [fonts["zh_serif"], fonts["latin_serif"]] if lang == "zh" \
        else [fonts["latin_serif"], fonts["zh_serif"]]
    sans = [fonts["zh_sans"], fonts["latin_sans"]] if lang == "zh" \
        else [fonts["latin_sans"], fonts["zh_sans"]]
    mono = fonts["mono"]
    fmt = lambda seq: ", ".join(typst_string(f) for f in seq if f)

    head = DOC_HEAD.format(
        title_lit=typst_string(title),
        serif_fonts=fmt(serif),
        sans_fonts=fmt(sans),
        mono_fonts=fmt([mono]),
        lang_lit=typst_string("zh" if lang == "zh" else "en"),
        extra_text=', hyphenate: true' if lang == "en" else "",
    )

    body = convert_markdown(md, render, indent)

    title_block = ""
    if title:
        title_block = (
            "#align(center)[\n"
            f"  #set text(font: ({fmt(sans)}), size: 20pt, weight: \"bold\")\n"
            f"  {escape_text(title)}\n"
            "]\n"
        )
        if subtitle:
            title_block += (
                "#align(center)[\n"
                f"  #set text(size: 11pt)\n  {escape_text(subtitle)}\n]\n"
            )
        title_block += "#v(14pt)\n"

    doc = head + "\n" + title_block + "\n" + body + "\n"
    return doc, tex


# ----------------------------------------------------------------------- CLI
def doctor(binary: str | None) -> int:
    print("md2pdf doctor (single-file / Typst)")
    print("-" * 56)
    if not binary:
        print("  - typst            MISSING  install a static binary or set MD2PDF_TYPST")
        print("                     https://github.com/typst/typst/releases")
        return 3
    try:
        ver = run_typst(binary, ["--version"]).stdout.strip()
    except (OSError, subprocess.SubprocessError) as exc:
        print(f"  - typst            BROKEN   {exc}")
        return 3
    print(f"  + typst            ok       {ver}  ({binary})")
    fonts = installed_fonts(binary)
    zh_serif = pick(fonts, ZH_SERIF)
    latin = pick(fonts, LATIN_SERIF)
    mono = pick(fonts, ["Consolas", "DejaVu Sans Mono", "Liberation Mono",
                        "Courier New", "Menlo", "monospace"])
    print(f"  {'+' if latin else '-'} latin serif      {'ok' if latin else 'MISSING':<8} {latin or 'none found'}")
    print(f"  {'+' if zh_serif else '-'} CJK serif        {'ok' if zh_serif else 'MISSING':<8} {zh_serif or 'install fonts-noto-cjk'}")
    print(f"  {'+' if mono else '-'} monospace        {'ok' if mono else 'MISSING':<8} {mono or 'any fixed-width font'}")
    print(f"  - platform         info     {sys.platform}, python {sys.version.split()[0]}")
    print("-" * 56)
    if latin and zh_serif:
        print("  READY    python md2pdf.py in.md out.pdf")
        return 0
    print("  NOT READY — a serif Latin face and a CJK face are both required")
    return 3


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        prog="md2pdf.py",
        description="Single-file Markdown → A4 PDF (Typst backend).",
    )
    ap.add_argument("input", nargs="?", help="input .md")
    ap.add_argument("output", nargs="?", help="output .pdf")
    ap.add_argument("title", nargs="?", default="", help="document title")
    ap.add_argument("subtitle", nargs="?", default="", help="subtitle / author line")
    ap.add_argument("--lang", choices=["zh", "en"], help="force the layout language")
    ap.add_argument("--doctor", action="store_true", help="check the environment")
    ap.add_argument("--keep-typ", action="store_true", help="keep the generated .typ next to the PDF")
    args = ap.parse_args(argv)

    binary = typst_binary()
    if args.doctor:
        return doctor(binary)

    if not args.input or not args.output:
        ap.print_usage(sys.stderr)
        print("error: input and output are required", file=sys.stderr)
        return 2
    if not os.path.isfile(args.input):
        print(f"error: no such file: {args.input}", file=sys.stderr)
        return 2
    if not binary:
        print("error: typst not found — install a static binary from "
              "https://github.com/typst/typst/releases and put it on PATH or in "
              "~/.cache/md2pdf/, or set MD2PDF_TYPST", file=sys.stderr)
        return 3

    fonts = installed_fonts(binary)
    resolved = {
        "zh_serif": pick(fonts, ZH_SERIF),
        "zh_sans": pick(fonts, ZH_SANS) or pick(fonts, ZH_SERIF),
        "latin_serif": pick(fonts, LATIN_SERIF),
        "latin_sans": pick(fonts, LATIN_SANS) or pick(fonts, LATIN_SERIF),
        "mono": pick(fonts, ["Consolas", "DejaVu Sans Mono", "Liberation Mono",
                             "Courier New", "Menlo"]) or "monospace",
    }
    if not resolved["latin_serif"]:
        print("error: no serif Latin font found; install one (e.g. fonts-dejavu-core)",
              file=sys.stderr)
        return 3

    with open(args.input, encoding="utf-8") as fh:
        md = fh.read()

    lang = args.lang or detect_lang(md)
    title = args.title or os.path.splitext(os.path.basename(args.input))[0]
    doc, tex = build_document(md, title, args.subtitle, lang, resolved)

    out_pdf = os.path.abspath(args.output)
    os.makedirs(os.path.dirname(out_pdf) or ".", exist_ok=True)
    typ_path = (os.path.splitext(out_pdf)[0] + ".typ") if args.keep_typ \
        else os.path.join(os.path.dirname(out_pdf), ".md2pdf.tmp.typ")
    with open(typ_path, "w", encoding="utf-8") as fh:
        fh.write(doc)

    proc = run_typst(binary, ["compile", "--root", os.path.dirname(typ_path) or ".",
                              typ_path, out_pdf])
    if not args.keep_typ:
        try:
            os.remove(typ_path)
        except OSError:
            pass
    if proc.returncode != 0:
        print((proc.stdout or "") + (proc.stderr or ""), file=sys.stderr)
        print(f"error: typst exited {proc.returncode}", file=sys.stderr)
        return 4
    if not os.path.isfile(out_pdf) or os.path.getsize(out_pdf) < 512:
        print(f"error: typst reported success but wrote no PDF at {out_pdf}",
              file=sys.stderr)
        return 5

    if tex.unknown:
        names = ", ".join(sorted(tex.unknown))
        print(f"warning: {len(tex.unknown)} unsupported TeX command(s) kept verbatim: {names}",
              file=sys.stderr)
    print(f"PDF -> {out_pdf}  (lang: {lang}, bytes: {os.path.getsize(out_pdf)})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
