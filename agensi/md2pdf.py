#!/usr/bin/env python3
"""md2pdf.py — single-file Markdown → A4 PDF, Typst backend.

Why this file exists
--------------------
Marketplace "skills" are delivered as text files only: binaries are listed but
never served, the whole listing must stay under 200 text files / 6M characters,
and a script is written to a temporary file and executed from there. So the
Chromium pipeline in the parent repo (369 files, 120 KaTeX font binaries) cannot
travel that way. This file is the smallest honest replacement:

    one Python file, standard library only, one external tool (typst).

It is not a CommonMark implementation. It covers what reports actually use —
headings, paragraphs, emphasis, inline code, fenced code, tables, lists, links,
block quotes, `\\( \\)` / `\\[ \\]` math — and says so instead of guessing.

Usage
-----
    python md2pdf.py in.md out.pdf ["Title"] ["Subtitle"] [--lang zh|en]
    python md2pdf.py --doctor

The `typst` binary is looked up in $MD2PDF_TYPST, then PATH, then
~/.cache/md2pdf/typst(.exe). Nothing is downloaded behind the user's back.

Exit codes: 0 ok, 2 usage, 3 typst missing, 4 typst failed, 5 output missing.
"""

