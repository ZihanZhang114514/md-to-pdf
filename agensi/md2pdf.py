# ---------------------------------------------------------------- environment
def typst_binary() -> str | None:
    env = os.environ.get("MD2PDF_TYPST")
    if env and os.path.isfile(env):
        return env
    found = shutil.which("typst")
    if found:
        return found
    for name in ("typst.exe", "typst"):
        cand = os.path.join(os.path.expanduser("~"), ".cache", "md2pdf", name)
        if os.path.isfile(cand):
            return cand
    return None


def run_typst(binary: str, args: list[str], timeout: int = 180) -> subprocess.CompletedProcess:
    return subprocess.run([binary, *args], capture_output=True, text=True,
                          encoding="utf-8", errors="replace", timeout=timeout)


def installed_fonts(binary: str) -> list[str]:
    try:
        proc = run_typst(binary, ["fonts"], timeout=120)
    except (OSError, subprocess.SubprocessError):
        return []
    if proc.returncode != 0:
        return []
    names = []
    for line in proc.stdout.splitlines():
        line = line.strip()
        if not line:
            continue
        # `typst fonts` prints "Family" and, for variable fonts, "Family (variable)"
        names.append(re.sub(r"\s*\((?:variable|variable, .*)\)$", "", line))
    return names


def pick(available: list[str], prefs: list[str]) -> str | None:
    lower = {n.lower(): n for n in available}
    for p in prefs:
        if p.lower() in lower:
            return lower[p.lower()]
    return None


# ---------------------------------------------------------------------- typst
def escape_text(s: str) -> str:
    """Escape Typst markup. `*`, `_`, `#`, `$`, `@`, `<`, `>`, `~` and `\\`
    are markup; everything else is literal."""
    out = []
    for ch in s:
        if ch in "\\#*_$@<>~`":
            out.append("\\" + ch)
        else:
            out.append(ch)
    return "".join(out)


def typst_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


class TexConverter:
    """TeX math → Typst math, for the subset reports actually use.

    Unknown commands are kept verbatim and reported, so a document never ends up
    with silently wrong maths.
    """

    def __init__(self) -> None:
        self.unknown: set[str] = set()

    def convert(self, tex: str) -> str:
        s = tex.strip()
        s = self._braced(s)
        s = self._scripts(s)
        s = self._commands(s)
        s = s.replace("\\\\", " \\ ")
        return re.sub(r"[ \t]+", " ", s).strip()

    # -- helpers ---------------------------------------------------------
    @staticmethod
    def _grab(s: str, i: int) -> tuple[str, int] | None:
        """Read one argument starting at s[i] (a {group} or a single token)."""
        while i < len(s) and s[i] in " \t\n":
            i += 1
        if i >= len(s):
            return None
        if s[i] == "{":
            depth, j = 0, i
            while j < len(s):
                if s[j] == "{":
                    depth += 1
                elif s[j] == "}":
                    depth -= 1
                    if depth == 0:
                        return s[i + 1:j], j + 1
                j += 1
            return s[i + 1:], len(s)
        if s[i] == "\\":
            m = re.match(r"\\[A-Za-z]+", s[i:])
            if m:
                return m.group(0), i + m.end()
            return s[i:i + 2], i + 2
        return s[i], i + 1

    def _mathrm(self, body: str) -> str:
        r"""\mathrm{mm^2} → upright("mm")^2: letters inside a string, scripts outside."""
        m = re.match(r"^([A-Za-z][A-Za-z ]*)(.*)$", body, re.S)
        if not m:
            return 'upright("' + body.replace('"', '\\"') + '")'
        head, rest = m.group(1).strip(), m.group(2)
        out = 'upright("' + head + '")'
        if rest.strip():
            out += self.convert(rest)
        return out
    def _two_args(self, s: str, name: str, emit: str | None = None) -> str:
        pat = re.compile(r"\\" + name + r"(?![A-Za-z])")
        while True:
            m = pat.search(s)
            if not m:
                return s
            a = self._grab(s, m.end())
            if not a:
                return s
            first, pos = a
            b = self._grab(s, pos)
            if not b:
                return s
            second, end = b
            inner1, inner2 = self.convert(first), self.convert(second)
            s = s[:m.start()] + f"{emit or name}({inner1}, {inner2})" + s[end:]

    def _braced(self, s: str) -> str:
        s = self._two_args(s, "frac")
        s = self._two_args(s, "dfrac", emit="frac")
        s = self._two_args(s, "tfrac", emit="frac")
        # \sqrt[n]{x} and \sqrt{x}
        while True:
            m = re.search(r"\\sqrt(?:\[([^\]]*)\])?", s)
            if not m:
                break
            arg = self._grab(s, m.end())
            if not arg:
                break
            body, end = arg
            if m.group(1):
                rep = f"root({self.convert(m.group(1))}, {self.convert(body)})"
            else:
                rep = f"sqrt({self.convert(body)})"
            s = s[:m.start()] + rep + s[end:]
        return s

    def _scripts(self, s: str) -> str:
        # TeX x^{a} / x_{a} becomes Typst x^(a) / x_(a)
        def fix(m: re.Match) -> str:
            return m.group(1) + "(" + self.convert(m.group(2)) + ")"
        return re.sub(r"([\^_])\{([^{}]*)\}", fix, s)

    def _commands(self, s: str) -> str:
        """Single left-to-right scan: an argument-taking command must consume its
        argument, otherwise the leftover `{...}` lands in the output."""
        out: list[str] = []
        i = 0
        symbols = {"%": "%", "{": "{", "}": "}", "$": "$", "&": "&",
                   "#": "#", "_": "_", "|": "|"}
        while i < len(s):
            if s[i] != "\\" or i + 1 >= len(s):
                out.append(s[i])
                i += 1
                continue
            nxt = s[i + 1]
            if nxt.isalpha():
                if out and out[-1][-1:].isalnum():
                    out.append(" ")
                m = re.match(r"\\([A-Za-z]+)", s[i:])
                name = m.group(1)
                j = i + m.end()
                if name in GREEK or name in OPERATORS:
                    out.append(GREEK.get(name) or OPERATORS[name])
                    # `\times10` must not become the identifier `times10`
                    if j < len(s) and (s[j].isalnum()):
                        out.append(" ")
                    i = j
                    continue
                if name in ACCENTS:
                    arg = self._grab(s, j)
                    if arg:
                        body, end = arg
                        if name == "text":
                            out.append('"' + body.replace('"', '\\"') + '"')
                        elif name == "operatorname":
                            out.append('op("' + body.replace('"', '\\"') + '")')
                        elif name == "mathrm":
                            out.append(self._mathrm(body))
                        else:
                            out.append(f"{ACCENTS[name]}({self.convert(body)})")
                        i = end
                        if i < len(s) and s[i].isalnum():
                            out.append(" ")
                        continue
                    out.append(name)
                    i = j
                    continue
                if name in ("left", "right", "big", "Big", "bigl", "bigr",
                            "middle", "displaystyle", "textstyle", "limits",
                            "nolimits"):
                    i = j
                    continue
                self.unknown.add("\\" + name)
                out.append("\\" + name)
                i = j
                continue
            pair = s[i:i + 2]
            if nxt in symbols:
                out.append(symbols[nxt])
                i += 2
                continue
            if nxt == "\\":           # \\ line break inside maths
                out.append(" \\ ")
                i += 2
                continue
            if nxt in ",;:!" or nxt == " ":
                out.append(" ")
                i += 2
                continue
            out.append(nxt)
            i += 2
        return "".join(out)


# -------------------------------------------------------------------- inline
PLACEHOLDER = re.compile("\x00([A-Z]{2})(\\d+)\x00")


class Renderer:
    def __init__(self, lang: str, tex: TexConverter) -> None:
        self.lang = lang
        self.tex = tex

    def inline(self, s: str) -> str:
        """Escape literal text and map emphasis / code / links to Typst."""
        tokens: list[str] = []

        def hold(value: str) -> str:
            tokens.append(value)
            return f"\x00TK{len(tokens) - 1}\x00"

        # A placeholder may already be present (math, restored later); keep it.
        s = PLACEHOLDER.sub(lambda m: hold("\x00" + m.group(1) + m.group(2) + "\x00"), s)

        pattern = re.compile(
            r"`([^`\n]+)`"                       # inline code
            r"|\*\*(.+?)\*\*"                    # bold
            r"|(?<![\w*])\*([^*\n]+)\*(?![\w*])"  # italic
            r"|\[([^\]]+)\]\(([^)\s]+)\)"        # link
        )
        out, pos = [], 0
        for m in pattern.finditer(s):
            out.append(escape_text(s[pos:m.start()]))
            if m.group(1) is not None:
                out.append(hold("`" + m.group(1).replace("`", "\\`") + "`"))
            elif m.group(2) is not None:
                out.append("*" + self.inline(m.group(2)) + "*")
            elif m.group(3) is not None:
                out.append("_" + self.inline(m.group(3)) + "_")
            else:
                out.append(f'#link("{m.group(5)}")[' + self.inline(m.group(4)) + "]")
            pos = m.end()
        out.append(escape_text(s[pos:]))
        text = "".join(out)

        def restore(m: re.Match) -> str:
            return tokens[int(m.group(1))]

        return re.sub("\x00TK(\\d+)\x00", restore, text)


# --------------------------------------------------------------------- blocks
FENCE = re.compile(r"^([ \t]*)(`{3,}|~{3,})[^\n]*\n[\s\S]*?^\1?\2[ \t]*$", re.M)
DISPLAY_MATH = re.compile(r"\\\[([\s\S]*?)\\\]")
INLINE_MATH = re.compile(r"\\\(([\s\S]*?)\\\)")
TABLE_SEP = re.compile(r"^\s*\|?[\s:|-]*-[\s:|-]*\|?\s*$")
HEADING = re.compile(r"^(#{1,6})\s+(.*)$")
ULIST = re.compile(r"^\s*[-*+]\s+(.*)$")
OLIST = re.compile(r"^\s*\d+[.)]\s+(.*)$")
QUOTE = re.compile(r"^>\s?(.*)$")
HR = re.compile(r"^\s*(?:---|\*\*\*|___)\s*$")


def split_row(line: str) -> list[str]:
    line = line.strip()
    if line.startswith("|"):
        line = line[1:]
    if line.endswith("|"):
        line = line[:-1]
    return [c.strip() for c in line.split("|")]


def convert_block_table(rows: list[str], render: Renderer) -> str:
    header = split_row(rows[0])
    aligns = []
    for cell in split_row(rows[1]):
        cell = cell.strip()
        if cell.startswith(":") and cell.endswith(":"):
            aligns.append("center")
        elif cell.endswith(":"):
            aligns.append("right")
        else:
            aligns.append("left")
    body = [split_row(r) for r in rows[2:]]
    ncols = max([len(header)] + [len(r) for r in body])
    while len(aligns) < ncols:
        aligns.append("left")

    def cell(text: str, bold: bool = False) -> str:
        inner = render.inline(text)
        return f"[*{inner}*]" if bold else f"[{inner}]"

    parts = [
        "#table(",
        f"  columns: {ncols},",
        f"  align: ({', '.join(aligns[:ncols])}),",
    ]
    parts += ["  " + cell(c, bold=True) + "," for c in header]
    for row in body:
        row = row + [""] * (ncols - len(row))
        parts += ["  " + cell(c) + "," for c in row[:ncols]]
    parts.append(")")
    return "\n".join(parts)


def convert_markdown(md: str, render: Renderer, indent: str) -> str:
    """Line-oriented block pass. Returns Typst markup for the document body."""
    md = md.replace("\r\n", "\n").replace("\r", "\n")

    fences: list[str] = []
    maths: list[str] = []

    def stash_fence(m: re.Match) -> str:
        fences.append(m.group(0))
        return f"\n\n\x00FN{len(fences) - 1}\x00\n\n"

    md = FENCE.sub(stash_fence, md)

    def stash_display(m: re.Match) -> str:
        maths.append(render.tex.convert(m.group(1)))
        return f"\n\n\x00DM{len(maths) - 1}\x00\n\n"

    def stash_inline(m: re.Match) -> str:
        maths.append(render.tex.convert(m.group(1)))
        return f"\x00IM{len(maths) - 1}\x00"

    md = DISPLAY_MATH.sub(stash_display, md)
    md = INLINE_MATH.sub(stash_inline, md)

    lines = md.split("\n")
    out: list[str] = []
    para: list[str] = []
    i = 0

    def flush_para() -> None:
        nonlocal para
        if not para:
            return
        text = ""
        for idx, piece in enumerate(para):
            if idx:
                prev = text[-1:] or " "
                nxt = piece[:1] or " "
                text += "" if (CJK_RE.search(prev) or CJK_RE.search(nxt)) else " "
            text += piece.strip()
        para = []
        if text.strip():
            out.append(indent + render.inline(text))

    while i < len(lines):
        line = lines[i]
        stripped = line.strip()

        if not stripped:
            flush_para()
            i += 1
            continue

        m = re.match(r"\x00FN(\d+)\x00", stripped)
        if m:
            flush_para()
            block = fences[int(m.group(1))]
            out.append(block)
            out.append("")
            i += 1
            continue

        m = re.match(r"\x00DM(\d+)\x00", stripped)
        if m:
            flush_para()
            out.append(f"$ {maths[int(m.group(1))]} $")
            out.append("")
            i += 1
            continue

        if HR.match(line):
            flush_para()
            out.append("#line(length: 100%, stroke: 0.4pt + luma(160))")
            i += 1
            continue

        m = HEADING.match(stripped)
        if m:
            flush_para()
            level = min(len(m.group(1)), 3)
            out.append(f"#heading(level: {level})[{render.inline(m.group(2))}]")
            i += 1
            continue

        if stripped.startswith("|") and "|" in stripped[1:]:
            if i + 1 < len(lines) and TABLE_SEP.match(lines[i + 1].strip()):
                rows = [line, lines[i + 1]]   # header + alignment row
                j = i + 2
                while j < len(lines) and lines[j].strip() and "|" in lines[j]:
                    rows.append(lines[j])
                    j += 1
                flush_para()
                out.append(convert_block_table(rows, render))
                out.append("")
                i = j
                continue
            # orphan pipe row (no separator line): keep it as literal text
            para.append(stripped)
            i += 1
            continue

        m = QUOTE.match(stripped)
        if m:
            flush_para()
            out.append(f"#quote(block: true)[{render.inline(m.group(1))}]")
            i += 1
            continue

        m = ULIST.match(line)
        if m:
            flush_para()
            items = []
            while i < len(lines) and ULIST.match(lines[i]):
                items.append("- " + render.inline(ULIST.match(lines[i]).group(1)))
                i += 1
            out.extend(items)
            out.append("")
            continue

        m = OLIST.match(line)
        if m:
            flush_para()
            while i < len(lines) and OLIST.match(lines[i]):
                out.append("+ " + render.inline(OLIST.match(lines[i]).group(1)))
                i += 1
            out.append("")
            continue

        para.append(stripped)
        i += 1

    flush_para()
    result = "\n\n".join(x for x in out if x is not None)
    return re.sub(r"\x00IM(\d+)\x00",
                  lambda m: "$" + maths[int(m.group(1))] + "$", result)


